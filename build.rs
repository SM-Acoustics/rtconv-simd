//! Classifies the compilation target as having a hardware FPU or not.
//!
//! Emits `cfg(rtconv_no_fpu)` for targets whose `f32` arithmetic would be software-emulated, so
//! `rtconv_simd::auto` can pick the Q1.15 / block-floating-point engines there.
//!
//! On stable Rust the RISC-V `F`/`D` extensions are not exposed as `cfg(target_feature)`
//! (`riscv32imafc-unknown-none-elf`, used by ESP32-P4, and `riscv32imac-unknown-none-elf`, used
//! by ESP32-C6, report identical cfgs), so the ISA string of the target triple is inspected.

use std::env;
use std::f64::consts::PI;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=TARGET");
    println!("cargo:rustc-check-cfg=cfg(rtconv_no_fpu)");

    emit_fpu_cfg();
    generate_fft_tables();
}

fn emit_fpu_cfg() {
    let target = env::var("TARGET").unwrap_or_default();
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let abi = env::var("CARGO_CFG_TARGET_ABI").unwrap_or_default();
    let features = env::var("CARGO_CFG_TARGET_FEATURE").unwrap_or_default();
    let has_feature = |name: &str| features.split(',').any(|f| f == name);
    let force_q15 = env::var_os("CARGO_FEATURE_NATIVE_Q15").is_some();

    let has_fpu = match arch.as_str() {
        "riscv32" | "riscv64" => {
            // ISA letters follow the width, e.g. "riscv32imafc" -> "imafc", "riscv64gc" -> "gc".
            let isa = target
                .split('-')
                .next()
                .unwrap_or("")
                .trim_start_matches("riscv32")
                .trim_start_matches("riscv64");
            has_feature("f")
                || has_feature("d")
                || isa
                    .split('_')
                    .next()
                    .unwrap_or("")
                    .contains(['f', 'd', 'g'])
        }
        "arm" => {
            abi == "eabihf"
                || ["vfp2", "vfp3", "vfp4", "fp-armv8"]
                    .iter()
                    .any(|f| has_feature(f))
        }
        "avr" | "msp430" => false,
        // ESP32-S2 (Xtensa LX7) has no FPU; ESP32 and ESP32-S3 do.
        "xtensa" => !target.contains("esp32s2"),
        _ => true,
    };

    if force_q15 || !has_fpu {
        println!("cargo:rustc-cfg=rtconv_no_fpu");
    }
}

/// Generates single-table quarter-wave twiddle ROMs in `OUT_DIR`:
/// - `simd_fft_tables_gen.rs`: `[f32; 4097]` (`16,388 B` ROM) for `N <= 16384`, computed in
///   `f64` (`p = 53`) and rounded to `f32` (`p = 24`) under IEEE 754 round-to-nearest-even.
/// - `fft_q15_tables_gen.rs`: `[i16; 513]` (`1,026 B` ROM) for `N <= 2048`, computed in `f64`
///   and rounded with round-to-nearest-even (`f64::round_ties_even`).
fn generate_fft_tables() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set"));

    // 1. f32 quarter-wave cosine table for N_MAX = 16384 (Q = 4096, 4097 entries = 16,388 B).
    const F32_N_MAX: usize = 16_384;
    const F32_Q: usize = F32_N_MAX / 4;
    let mut f32_src = String::with_capacity(F32_Q * 24 + 512);
    f32_src.push_str(
        "// Auto-generated by build.rs: IEEE 754 f64->f32 RNE quarter-wave cosine table.\n",
    );
    let _ = writeln!(
        f32_src,
        "pub(crate) const MAX_FFT_SIZE: usize = {F32_N_MAX};"
    );
    let _ = writeln!(f32_src, "pub(crate) const TW_QUARTER: usize = {F32_Q};");
    let _ = writeln!(
        f32_src,
        "pub(crate) static TW_COS_Q: [f32; {}] = [",
        F32_Q + 1
    );
    for k in 0..=F32_Q {
        let val: f32 = if k == 0 {
            1.0f32
        } else if k == F32_Q {
            0.0f32
        } else {
            let angle = 2.0 * PI * (k as f64) / (F32_N_MAX as f64);
            angle.cos() as f32
        };
        let bits = val.to_bits();
        let _ = writeln!(f32_src, "    f32::from_bits(0x{bits:08x}),");
    }
    f32_src.push_str("];\n");
    fs::write(out_dir.join("simd_fft_tables_gen.rs"), f32_src)
        .expect("failed to write simd_fft_tables_gen.rs");

    // 2. Q1.15 quarter-wave cosine table for N_MAX = 2048 (Q = 512, 513 entries = 1,026 B).
    const Q15_N_MAX: usize = 2_048;
    const Q15_Q: usize = Q15_N_MAX / 4;
    let mut q15_src = String::with_capacity(Q15_Q * 8 + 512);
    q15_src.push_str(
        "// Auto-generated by build.rs: Q1.15 RNE quarter-wave cosine table for N <= 2048.\n",
    );
    let _ = writeln!(
        q15_src,
        "pub(crate) const MAX_Q15_FFT_SIZE: usize = {Q15_N_MAX};"
    );
    let _ = writeln!(q15_src, "pub(crate) const Q15_TW_QUARTER: usize = {Q15_Q};");
    let _ = writeln!(
        q15_src,
        "pub(crate) static TWIDDLE_COS_Q_2048: [i16; {}] = [",
        Q15_Q + 1
    );
    for k in 0..=Q15_Q {
        let val: i16 = if k == 0 {
            i16::MAX
        } else if k == Q15_Q {
            0
        } else {
            let angle = 2.0 * PI * (k as f64) / (Q15_N_MAX as f64);
            let scaled = (32768.0 * angle.cos()).round_ties_even() as i32;
            scaled.clamp(i16::MIN as i32, i16::MAX as i32) as i16
        };
        let _ = writeln!(q15_src, "    {val},");
    }
    q15_src.push_str("];\n");
    fs::write(out_dir.join("fft_q15_tables_gen.rs"), q15_src)
        .expect("failed to write fft_q15_tables_gen.rs");
}
